internal fun SessionSnapshot.toHtml(): String = buildString {
    append("<!doctype html>\n<html lang=\"en\">\n<head>\n")
    append("<meta charset=\"utf-8\">\n")
    append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
    append("<title>FrameHUD · ").append(escapeHtml(packageName)).append("</title>\n")
    append("<style>").append(REPORT_CSS).append("</style>\n</head>\n<body>\n")

    appendHeader(this@toHtml)
    appendVerdict(this@toHtml)
    appendConfidence(this@toHtml)
    appendMeasurement(this@toHtml)
    appendStats(this@toHtml)
    appendWindow(this@toHtml)
    appendWorstFrames(this@toHtml)
    appendEnvironment(this@toHtml)

    append("<footer>Generated by FrameHUD ").append(escapeHtml(frameHudVersion))
    append(". Measurements never leave the device.</footer>\n")
    append("</body>\n</html>\n")
}

private fun StringBuilder.appendHeader(snapshot: SessionSnapshot) = with(snapshot) {
    append("<header>\n<h1>FrameHUD session</h1>\n<p class=\"meta\">")
    append(escapeHtml(packageName))
    appVersionName?.let { append(' ').append(escapeHtml(it)) }
    append(" (").append(appVersionCode).append(")")
    append(" · ").append(escapeHtml(manufacturer)).append(' ').append(escapeHtml(model))
    append(", API ").append(apiLevel)
    append(" · ").append(escapeHtml(formatTimestamp(takenAtEpochMs)))
    append("</p>\n</header>\n")
}

private fun StringBuilder.appendVerdict(snapshot: SessionSnapshot) = with(snapshot) {
    append("<section class=\"tiles\">\n")
    appendTile(formatCount(session.frames), "frames")
    appendTile(formatMs(session.p95FrameMs), "p95")
    appendTile(formatPercent(session.jankPercent), "jank")
    appendTile(formatCount(session.frozenFrames), "frozen")
    append("</section>\n")
}

private fun StringBuilder.appendTile(value: String, label: String) {
    append("<div class=\"tile\"><strong>").append(value).append("</strong><span>").append(label)
    append("</span></div>\n")
}

private fun StringBuilder.appendConfidence(snapshot: SessionSnapshot) {
    append("<section>\n<h2>Measurement confidence</h2>\n")
    val sessionIssues = snapshot.session.confidence.issues
    val screenOnlyIssues = snapshot.screen.confidence.issues - sessionIssues.toSet()
    if (sessionIssues.isEmpty() && screenOnlyIssues.isEmpty()) {
        append("<p class=\"meta\">No issues.</p>\n</section>\n")
        return
    }
    append("<ul>\n")
    for (issue in sessionIssues) appendIssue(issue.summary)
    for (issue in screenOnlyIssues) appendIssue("${issue.summary} — this screen only")
    append("</ul>\n</section>\n")
}

private fun StringBuilder.appendIssue(summary: String) {
    append("<li>").append(escapeHtml(summary)).append("</li>\n")
}

private fun StringBuilder.appendMeasurement(snapshot: SessionSnapshot) = with(snapshot) {
    append("<section>\n<h2>Measurement</h2>\n<table>\n")
    appendRow("State", measurementState())
    appendRow("Screen", screenName?.let(::escapeHtml) ?: "—")
    appendRow("Mark", mark?.let(::escapeHtml) ?: "—")
    if (context.isNotEmpty()) {
        val chips = context.entries.joinToString(separator = " ") { (key, value) ->
            "<code>${escapeHtml(key)}=${escapeHtml(value)}</code>"
        }
        appendRow("Context", chips)
    }
    appendRow("Display", "${formatFloat(display.refreshRateHz)} Hz, budget ${formatMs(display.frameBudgetMs)}")
    append("</table>\n</section>\n")
}

private fun SessionSnapshot.measurementState(): String = when {
    !isEnabled -> "disabled"
    isFrozen -> "collecting, readings frozen"
    else -> "collecting"
}

private fun StringBuilder.appendStats(snapshot: SessionSnapshot) = with(snapshot) {
    append("<section>\n<h2>Stats</h2>\n<table>\n")
    append("<tr><th></th><th>Session</th><th>Screen</th></tr>\n")
    appendStatRow("Frames", session, screen) { formatCount(it.frames) }
    appendStatRow("Duration", session, screen) { formatSeconds(it.durationMs) }
    appendStatRow("p50", session, screen) { formatMs(it.p50FrameMs) }
    appendStatRow("p95", session, screen) { formatMs(it.p95FrameMs) }
    appendStatRow("p99", session, screen) { formatMs(it.p99FrameMs) }
    appendStatRow("Jank", session, screen) { formatPercent(it.jankPercent) }
    appendStatRow("Lost time", session, screen) { formatMs(it.lostTimeMs) }
    appendStatRow("Frozen frames", session, screen) { formatCount(it.frozenFrames) }
    appendStatRow("Longest jank streak", session, screen) { formatCount(it.maxJankStreak) }
    appendStatRow("Dropped reports", session, screen) { formatCount(it.droppedReports) }
    append("</table>\n")
    if (session.droppedReports > 0) {
        append("<p class=\"caution\">Dropped reports above zero: every other figure is undersampled.</p>\n")
    }
    append("</section>\n")
}

private fun StringBuilder.appendStatRow(
    label: String,
    session: SessionStats,
    screen: SessionStats,
    format: (SessionStats) -> String,
) {
    append("<tr><th>").append(label).append("</th><td>").append(format(session))
    append("</td><td>").append(format(screen)).append("</td></tr>\n")
}

private fun StringBuilder.appendWindow(snapshot: SessionSnapshot) {
    append("<section>\n<h2>Frame window</h2>\n")
    val window = snapshot.window
    if (window.history.size == 0) {
        append("<p class=\"meta\">No frames in the window.</p>\n</section>\n")
        return
    }
    append("<p class=\"meta\">Last ").append(window.history.size).append(" frames: p95 ")
    append(formatMs(window.p95FrameMs)).append(" · worst ").append(formatMs(window.worstFrameMs))
    append(" · red bars ran past their deadline. ")
    append(window.fps).append(" frames in the last second.</p>\n")
    appendFrameChart(window.history)
    appendPhases(snapshot.phases)
    append("</section>\n")
}

private fun StringBuilder.appendFrameChart(history: FrameHistory) {
    var scaleMs = 0f
    for (index in 0 until history.size) {
        scaleMs = max(scaleMs, max(history.totalMsAt(index), history.deadlineMsAt(index)))
    }
    if (scaleMs <= 0f) return
    scaleMs *= CHART_HEADROOM

    append("<svg viewBox=\"0 0 $CHART_WIDTH $CHART_HEIGHT\" preserveAspectRatio=\"none\" role=\"img\" ")
    append("aria-label=\"Recent frame durations\">\n")
    val step = CHART_WIDTH / history.size
    val barWidth = step * CHART_BAR_SHARE
    for (index in 0 until history.size) {
        val totalMs = history.totalMsAt(index)
        val deadlineMs = history.deadlineMsAt(index)
        val height = CHART_HEIGHT * (totalMs / scaleMs)
        val cssClass = if (totalMs > deadlineMs) "janky" else "ok"
        append("<rect class=\"").append(cssClass).append("\" x=\"").append(formatFloat(step * index))
        append("\" y=\"").append(formatFloat(CHART_HEIGHT - height))
        append("\" width=\"").append(formatFloat(barWidth))
        append("\" height=\"").append(formatFloat(height)).append("\"/>\n")

        val deadlineY = CHART_HEIGHT * (1f - deadlineMs / scaleMs)
        append("<line class=\"deadline\" x1=\"").append(formatFloat(step * index))
        append("\" x2=\"").append(formatFloat(step * index + barWidth))
        append("\" y1=\"").append(formatFloat(deadlineY))
        append("\" y2=\"").append(formatFloat(deadlineY)).append("\"/>\n")
    }
    append("</svg>\n")
}

private fun StringBuilder.appendPhases(phases: FramePhases) {
    append("<p class=\"meta\">")
    append(phases.bottleneckStage.name.lowercase(Locale.US))
    append(" bound at ").append(formatMs(phases.bottleneck.average)).append(" per frame</p>\n")
    append("<table>\n<tr><th></th><th>Average</th><th>Peak since reset</th></tr>\n")
    appendPhaseRow("Delay before start", phases.unknownDelay)
    appendPhaseRow("Input", phases.input)
    appendPhaseRow("Animation", phases.animation)
    appendPhaseRow("Layout", phases.layout)
    appendPhaseRow("Draw", phases.draw)
    appendPhaseRow("UI thread", phases.cpu)
    appendPhaseRow("Sync", phases.sync)
    appendPhaseRow("Command issue", phases.commandIssue)
    appendPhaseRow("Swap buffers", phases.swapBuffers)
    appendPhaseRow("Render thread", phases.render)
    if (phases.isGpuAvailable) appendPhaseRow("GPU", phases.gpu)
    appendPhaseRow("Unattributed", phases.other)
    appendPhaseRow("Total", phases.total)
    appendPhaseRow("Overrun", phases.overrun)
    append("</table>\n")
}

private fun StringBuilder.appendPhaseRow(label: String, value: MetricValue) {
    append("<tr><th>").append(label).append("</th><td>").append(formatMs(value.average))
    append("</td><td>").append(value.peak?.let(::formatMs) ?: "—").append("</td></tr>\n")
}

private fun StringBuilder.appendWorstFrames(snapshot: SessionSnapshot) {
    if (snapshot.worstFrames.isEmpty()) return
    append("<section>\n<h2>Worst frames</h2>\n<table>\n")
    append("<tr><th>Time</th><th>Duration</th></tr>\n")
    for (frame in snapshot.worstFrames) {
        append("<tr><td>").append(escapeHtml(snapshot.formatTimeOfDay(snapshot.frameEndEpochMs(frame.endNs))))
        append("</td><td>").append(formatMs(frame.totalMs)).append("</td></tr>\n")
    }
    append("</table>\n</section>\n")
}

private fun StringBuilder.appendEnvironment(snapshot: SessionSnapshot) = with(snapshot) {
    append("<section>\n<h2>Environment</h2>\n<table>\n")
    appendRow("Heap", "${memory.usedHeapMb} of ${memory.maxHeapMb} MB, peak ${memory.peakUsedHeapMb} MB")
    appendRow("Native heap", "${memory.nativeHeapMb} MB, peak ${memory.peakNativeHeapMb} MB")
    appendRow("GC since reset", "${memory.gcCount} runs, ${memory.gcTimeMs} ms")
    val headroom = thermal.headroom?.let { ", headroom ${formatFloat(it)}" }.orEmpty()
    appendRow("Thermal", thermal.level.name.lowercase(Locale.US) + headroom)
    append("</table>\n")
    if (thermal.level.isThrottling) {
        append("<p class=\"caution\">Thermal throttling: timings are not comparable to a cold run.</p>\n")
    }
    append("</section>\n")
}

private fun StringBuilder.appendRow(label: String, value: String) {
    append("<tr><th>").append(label).append("</th><td>").append(value).append("</td></tr>\n")
}

private fun formatMs(value: Float): String = "${formatFloat(value)} ms"

private fun formatPercent(value: Float): String = "${formatFloat(value)}%"

private fun formatSeconds(durationMs: Long): String = String.format(Locale.US, "%.1f s", durationMs / MS_PER_SECOND_D)

private fun formatCount(value: Int): String = value.toString()

private fun formatFloat(value: Float): String = String.format(Locale.US, "%.1f", value)

internal fun escapeHtml(value: String): String = buildString(value.length) {
    for (char in value) {
        when (char) {
            '&' -> append("&amp;")
            '<' -> append("&lt;")
            '>' -> append("&gt;")
            '"' -> append("&quot;")
            '\'' -> append("&#39;")
            else -> append(char)
        }
    }
}

